namespace BazisGUI.MasterInterface.Interfaces
{
    /// <summary>
    /// Мастер, представление которого построено на Avalonia.
    /// </summary>
    /// <remarks>
    /// Функциональная часть мастера описана в <see cref="IBaseMaster"/> и не зависит от UI-фреймворка,
    /// а этот интерфейс добавляет к ней только способ получить представление.
    /// Реализация не должна знать, во что представление будет встроено: на текущем этапе это
    /// WinForms-хост оболочки приложения, после перевода оболочки на Avalonia — сама оболочка.
    /// </remarks>
    public interface IAvaloniaMaster : IBaseMaster
    {
        /// <summary>
        /// Создаёт представление мастера.
        /// </summary>
        /// <remarks>
        /// Вызывается в UI-потоке Avalonia при каждом показе мастера, поэтому реализация
        /// должна возвращать новый экземпляр представления, а не переиспользовать предыдущий.
        /// </remarks>
        /// <returns>Представление мастера.</returns>
        Avalonia.Controls.Control CreateView();
    }
}
