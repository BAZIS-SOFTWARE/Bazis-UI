using WinGUI.Masters.Args;

namespace MasterInterface.Interfaces
{
    /// <summary>
    /// Базовый интерфейс для "мастер"-компонентов, предоставляющий общие события и
    /// операции отправки команд к устройству/мастеру.
    /// </summary>
    /// <remarks>
    /// Реализации этого интерфейса отвечают за:
    /// - публикацию информационных и служебных событий, связанных с работой мастера;
    /// - приём и отправку одиночных команд через настраиваемый исполнитель команд.
    /// Потокобезопасность подписки на события и выполнения команд зависит от конкретной реализации.
    /// </remarks>
    public interface IBaseMaster : IMasterInterface
    {
        /// <summary>
        /// Событие публикации информационных сообщений для печати/логирования.
        /// Аргументы содержат текст и дополнительные параметры форматирования.
        /// </summary>
        event EventHandler<PrintInfoEventArgs> PrintInfoEvent;

        /// <summary>
        /// Событие запроса генерации условий/параметров (например, для тестов или сценариев).
        /// Аргументы содержат требуемые параметры и место для результата генерации.
        /// </summary>
        event EventHandler<GenerateConditionsEventArgs> GenerateConditionsEvent;

        /// <summary>
        /// Событие, вызываемое при обновлении сцены/состояния отображения.
        /// Аргументы содержат информацию об изменениях, необходимых для UI или визуализации.
        /// </summary>
        event EventHandler<UpdateSceneEventArgs> UpdateSceneEvent;

        /// <summary>
        /// Событие, сигнализирующее о завершении загрузки мастера и готовности к работе.
        /// Может использоваться для инициализации зависимых компонентов.
        /// </summary>
        event EventHandler<EventArgs> OnMasterLoaded;

        /// <summary>
        /// Устанавливает функцию-исполнитель для отправки одиночной команды.
        /// </summary>
        /// <param name="executeCommand">
        /// Делегат, принимающий текст команды и возвращающий <see cref="Task{String}"/>
        /// с ответом устройства. Если передается <c>null</c>, текущий исполнитель должен быть снят/очищен
        /// (реализация может трактовать это как сброс в состояние по умолчанию).
        /// </param>
        /// <remarks>
        /// Этот метод используется для внедрения конкретной логики отправки команд (напр., тестовый мок,
        /// адаптер к разному каналу связи). Делегат должен быть асинхронным и не блокировать поток.
        /// Реализация должна учитывать возможность множественных вызовов и корректно заменять/удалять исполнитель.
        /// </remarks>
        void SetCommandExecutor(Func<string, Task<string>> executeCommand);

        /// <summary>
        /// Асинхронно отправляет одну команду и возвращает ответ в виде строки.
        /// </summary>
        /// <param name="command">Текст команды для отправки. Не должен быть <c>null</c>.</param>
        /// <returns>
        /// Задача, представляющая асинхронную операцию. Результат — строка с ответом мастера/устройства.
        /// </returns>

        Task<string> SendCommandAsync(string command);

        /// <summary>
        /// Читаемое имя мастера. Используется для идентификации в UI, логах и диагностике.
        /// </summary>
        string MasterName { get; }
    }
}
